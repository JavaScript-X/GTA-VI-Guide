export function normalizeLocale(locale) {
  const code = String(locale || defaultLocale).toLowerCase().split("-")[0];
  return dictionary[code] ? code : defaultLocale;
}

export function languageDir(locale) {
  return languages.find((language) => language.code === normalizeLocale(locale))?.dir || "ltr";
}

export function t(locale, key) {
  const normalized = normalizeLocale(locale);
  return dictionary[normalized]?.[key] || dictionary[defaultLocale][key] || key;
}
